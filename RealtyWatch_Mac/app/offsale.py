"""Снятие с продажи по итогам прогонов — по квартире целиком, а не по одному сайту.

Сайт перестал показывать объявление в поиске, а открыть его страницу не удалось (Авито на проверках
отвечает капчей) — значит, попасть на это объявление нельзя: ссылка на сайт в карточке бесполезна,
и программа её убирает. Но та же квартира может продаваться на других сайтах, поэтому снятой она
считается, только когда её не осталось нигде: ни в поиске сайтов, ни на страницах объявлений.

Так решается перекос, при котором у сайта без рабочей проверки страниц объявления только копились:
в поиске их давно нет, снятыми они не становились, и рынок выглядел больше, чем он есть.
"""
from collections import defaultdict

from . import db

# Полных прогонов подряд без объявления в поиске, после которых считаем, что на этом сайте его уже нет.
# Один прогон — мало: выдача могла не доехать до конца. Счётчик растёт только после прогонов, которым
# можно верить: при неполной выдаче и при массовом пропадании снятие вообще не проверяется.
GONE_AFTER = 2


def _runs(n):
    return "прогон" if n % 10 == 1 and n % 100 != 11 else "прогона" if 2 <= n % 10 <= 4 and not 10 <= n % 100 < 20 else "прогонов"


def off_search(row):
    """Объявления нет в поиске своего сайта столько прогонов подряд, что ссылка уже никуда не ведёт."""
    return (row["missed"] or 0) >= GONE_AFTER


def gone(row):
    """Объявления на сайте больше нет: сайт показал его снятым или оно пропало из поиска насовсем."""
    return not row["active"] or off_search(row)


def reconcile(con, run_id=None, log=lambda m: None):
    """После прогона: квартиры, которых не осталось ни на одном сайте, уходят из продажи.
    Возвращает, сколько объявлений сняли."""
    from .runner import SOURCE_LABEL  # импорт здесь: runner сам пользуется этим модулем

    objs = defaultdict(list)
    for r in con.execute("SELECT source, source_id, object_id, active, missed, COALESCE(imported_only, 0) AS imported_only FROM listings"):
        objs[r["object_id"] or f"{r['source']}:{r['source_id']}"].append(dict(r))
    off = 0
    for items in objs.values():
        alive = [r for r in items if r["active"]]
        if not alive or any((not off_search(r)) or r["imported_only"] for r in alive):
            continue  # хоть одно объявление ещё в поиске или пришло выборочным импортом — не снимаем автоматически
        for r in alive:
            n = r["missed"] or 0
            reason = f"нет в поиске {SOURCE_LABEL.get(r['source'], r['source'])} {n} {_runs(n)} подряд, страницу проверить не удалось"
            if len(items) > 1:
                reason += "; на других сайтах объявления тоже нет"
            db.remove(con, r["source"], r["source_id"], reason, run_id)
            off += 1
    if off:
        con.commit()
        log(f"снято с продажи: {off} — этих объявлений не осталось ни в поиске сайтов, ни на их страницах")
    return off
